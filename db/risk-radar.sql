CREATE TABLE IF NOT EXISTS risk_radar (
  risk_id text PRIMARY KEY,
  risk_title text NOT NULL CHECK (length(trim(risk_title)) > 0),
  risk_type text NOT NULL DEFAULT '',
  iso text NOT NULL DEFAULT '',
  country text NOT NULL CHECK (length(trim(country)) > 0),
  rationale text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT '',
  intensity_of_hazard text NOT NULL DEFAULT '',
  impact text NOT NULL DEFAULT '',
  probability text NOT NULL DEFAULT '',
  risk_level text NOT NULL DEFAULT '',
  risk_trend text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT '',
  what_materialised text NOT NULL DEFAULT '',
  hazard_materialisation text NOT NULL DEFAULT '',
  materialisation_sources text NOT NULL DEFAULT '',
  triggers text NOT NULL DEFAULT '',
  current_vulnerability text NOT NULL DEFAULT '',
  current_vulnerability_sources text NOT NULL DEFAULT '',
  expected_exposure text NOT NULL DEFAULT '',
  expected_impact text NOT NULL DEFAULT '',
  expected_impact_sources text NOT NULL DEFAULT '',
  expected_priority_needs text NOT NULL DEFAULT '',
  impact_materialisation_description text NOT NULL DEFAULT '',
  rationale_update text NOT NULL DEFAULT '',
  source_row integer UNIQUE CHECK (source_row BETWEEN 1 AND 10),
  created_at timestamptz NOT NULL DEFAULT now()
);
